/**
 * Copy the shared Ask and projection prompts (../prompts) into
 * server/prompts.generated.ts, so the website's AI function carries them in
 * its bundle (Netlify functions can't read files outside frontend/).
 * Schemas lose their "$comment" (structured outputs don't take it).
 *
 * Run after editing prompts/: npm run prompts
 * A test (src/ai/web-prompts.test.ts) fails when the copy is out of date.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const promptsDir = join(here, "..", "..", "prompts");
const out = join(here, "..", "server", "prompts.generated.ts");

const tasks = ["ask", "projection"];
const entries = tasks.map((task) => {
  const prompt = readFileSync(join(promptsDir, `${task}.md`), "utf8");
  const schema = JSON.parse(readFileSync(join(promptsDir, `${task}.schema.json`), "utf8"));
  delete schema.$comment;
  return `  ${task}: {\n    prompt: ${JSON.stringify(prompt)},\n    schema: ${JSON.stringify(schema)},\n  },`;
});

writeFileSync(
  out,
  [
    "// Generated by scripts/bundle-prompts.mjs from /prompts. Do not edit: run `npm run prompts`.",
    'import type { WebAiTask, WebPrompt } from "./ai";',
    "",
    "export const WEB_PROMPTS: Record<WebAiTask, WebPrompt> = {",
    ...entries,
    "};",
    "",
  ].join("\n"),
);
console.log(`Wrote ${out}`);
